# C. Operator Precedence

# 9. Calculate 10 + 5 * 2
print(10 + 5 * 2)      # 20


# 10. Calculate (10 + 5) * 2
print((10 + 5) * 2)    # 30


# 11. Calculate 20 - 4 * 3
print(20 - 4 * 3)      # 8


# 12. Calculate (20 - 4) * 3
print((20 - 4) * 3)    # 48


# 13. Calculate 2 + 3 ** 2
print(2 + 3 ** 2)      # 11


# 14. Calculate (2 + 3) ** 2
print((2 + 3) ** 2)    # 25


# 15. Calculate 10 + 6 * 2 - 8 / 4
