# D. Floor Division and Modulus

# 17. 23 students, 5 students in each group
students = 23
group_size = 5

print(students // group_size)  # 4 complete groups
print(students % group_size)   # 3 students remain


# 18. 47 products, 6 products in each box
products = 47
box_size = 6

print(products // box_size)    # 7 complete boxes
print(products % box_size)     # 5 products remain


